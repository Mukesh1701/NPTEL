export function shuffleQuestionOptions(question: Question): Question {
  if (!question.options || question.options.length <= 1) {
    return { ...question };
  }

  // Preserve standard True/False option layout (A: True, B: False)
  const optTexts = question.options.map((o) => o.text.trim().toLowerCase());
  if (
    optTexts.length === 2 &&
    optTexts.includes('true') &&
    optTexts.includes('false')
  ) {
    const trueOpt = question.options.find((o) => o.text.trim().toLowerCase() === 'true')!;
    const isTrueCorrect = question.correctAnswers.includes(trueOpt.id);
    return {
      ...question,
      options: [
        { id: 'A', text: 'True' },
        { id: 'B', text: 'False' },
      ],
      correctAnswers: isTrueCorrect ? ['A'] : ['B'],
    };
  }

  const optionLetters = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'];

  // Keep track of each option and its original ID
  const optionsWithOrig = question.options.map((opt) => ({
    originalId: opt.id,
    text: opt.text,
  }));

  // Fisher-Yates shuffle
  const shuffled = [...optionsWithOrig];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  // Ensure the options order is actually jumbled and not identical to original
  if (
    shuffled.length > 1 &&
    shuffled.every((opt, idx) => opt.originalId === question.options[idx].id)
  ) {
    [shuffled[0], shuffled[1]] = [shuffled[1], shuffled[0]];
  }

  // Re-assign IDs (A, B, C, D...) based on their new positions
  const newOptions: Option[] = shuffled.map((item, idx) => ({
    id: optionLetters[idx] || String.fromCharCode(65 + idx),
    text: item.text,
  }));

  // Re-map correctAnswers to point to the new letter IDs
  const newCorrectAnswers = shuffled
    .map((item, idx) => {
      if (question.correctAnswers.includes(item.originalId)) {
        return newOptions[idx].id;
      }
      return null;
    })
    .filter((id): id is string => id !== null);

  return {
    ...question,
    options: newOptions,
    correctAnswers: newCorrectAnswers,
  };
}

export function getQuestionsByWeek(week: number): Question[] {
  return QUESTION_BANK.filter((q) => q.week === week).map(shuffleQuestionOptions);
}

export function getAllQuestions(): Question[] {
  return QUESTION_BANK.map(shuffleQuestionOptions);
}

export function getMultipleChoiceQuestions(): Question[] {
  return QUESTION_BANK.filter(
    (q) => q.type === 'multiple_choice'
  ).map(shuffleQuestionOptions);
}

export function isTrueFalseQuestion(q: Question): boolean {
  const optTexts = q.options.map((o) => o.text.trim().toLowerCase());
  const hasTrueFalseOptions =
    optTexts.length === 2 &&
    optTexts.includes('true') &&
    optTexts.includes('false');
  const asksTrueFalse =
    q.question.toLowerCase().includes('true or false') ||
    q.question.toLowerCase().includes('true/false');
  return hasTrueFalseOptions || asksTrueFalse;
}

export function getTrueFalseQuestions(): Question[] {
  return QUESTION_BANK.filter(isTrueFalseQuestion).map(shuffleQuestionOptions);
}

export function getWeekNumbers(): number[] {
  return Array.from({ length: 12 }, (_, i) => i + 1);
}
